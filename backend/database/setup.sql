create index if not exists idx_universities_country_id on public.universities(country_id);
create index if not exists idx_universities_lower_name on public.universities(lower(name));
create index if not exists idx_universities_tuition_min on public.universities(tuition_min);
create index if not exists idx_universities_tuition_max on public.universities(tuition_max);

create index if not exists idx_programs_university_id on public.programs(university_id);
create index if not exists idx_programs_degree_level on public.programs(degree_level);
create index if not exists idx_programs_field on public.programs(field);

create index if not exists idx_intakes_university_id on public.intakes(university_id);

create index if not exists idx_language_requirements_university_id on public.language_requirements(university_id);
-- Expression index so ON CONFLICT DO NOTHING also catches rows where degree_level is NULL
create unique index if not exists idx_language_requirements_unique_coalesce
  on public.language_requirements(university_id, test_name, coalesce(degree_level, ''));

create index if not exists idx_scholarships_university_id on public.scholarships(university_id);
create index if not exists idx_scholarships_country_id on public.scholarships(country_id);
-- Expression index so ON CONFLICT DO NOTHING also catches country-wide rows where university_id is NULL
create unique index if not exists idx_scholarships_unique_coalesce
  on public.scholarships(name, coalesce(university_id, -1));

-- -----------------------------------------------------------------------------
-- 3. AUTH SYNC TRIGGER (auth.users -> public.profiles)
-- -----------------------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data->>'full_name', '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

