-- -----------------------------------------------------------------------------
-- 1. TABLES
-- -----------------------------------------------------------------------------

create table if not exists public.countries (
  id bigint generated by default as identity primary key,
  name text not null unique,
  code text,
  capital text,
  region text,
  official_language text,
  currency text,
  flag_emoji text,
  description text,
  living_cost_monthly numeric,
  visa_info text,
  created_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  full_name text,
  phone text,
  nationality text,
  education_level text,
  gpa numeric(3,2) check (gpa >= 0 and gpa <= 4),
  ielts_score numeric(2,1) check (ielts_score >= 0 and ielts_score <= 9),
  preferred_country_id bigint references public.countries(id) on delete set null,
  preferred_degree_level text,
  preferred_field text,
  budget_max numeric check (budget_max >= 0),
  is_admin boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.universities (
  id bigint generated by default as identity primary key,
  country_id bigint not null references public.countries(id) on delete cascade,
  name text not null,
  city text,
  description text,
  website text,
  world_ranking int,
  tuition_min numeric,
  tuition_max numeric,
  student_count int,
  founded_year int,
  logo_url text,
  created_at timestamptz not null default now(),
  unique (country_id, name)
);

create table if not exists public.programs (
  id bigint generated by default as identity primary key,
  university_id bigint not null references public.universities(id) on delete cascade,
  name text not null,
  degree_level text check (degree_level in ('Bachelor', 'Master', 'PhD', 'Diploma')),
  field text,
  duration_months int,
  tuition_per_year numeric,
  description text,
  created_at timestamptz not null default now(),
  unique (university_id, name, degree_level)
);

create table if not exists public.intakes (
  id bigint generated by default as identity primary key,
  university_id bigint not null references public.universities(id) on delete cascade,
  name text not null,
  season text,
  start_date date,
  application_deadline date,
  is_open boolean not null default true,
  created_at timestamptz not null default now(),
  unique (university_id, name)
);

create table if not exists public.language_requirements (
  id bigint generated by default as identity primary key,
  university_id bigint not null references public.universities(id) on delete cascade,
  test_name text not null check (test_name in ('IELTS', 'TOEFL iBT', 'PTE Academic', 'Duolingo')),
  min_overall numeric,
  min_each_band numeric,
  degree_level text,
  notes text,
  created_at timestamptz not null default now(),
  unique (university_id, test_name, degree_level)
);

create table if not exists public.scholarships (
  id bigint generated by default as identity primary key,
  university_id bigint references public.universities(id) on delete cascade,
  country_id bigint references public.countries(id) on delete set null,
  name text not null,
  description text,
  amount numeric,
  coverage text,
  min_gpa numeric,
  min_ielts numeric,
  degree_level text,
  deadline date,
  url text,
  created_at timestamptz not null default now(),
  unique (name, university_id)
);

